# Generate 128 Public IPs (TEST-NET-2 block: 198.51.100.1 to 198.51.100.128)
SEED_IPS = [f"198.51.100.{i}" for i in range(1, 129)]

def _slugify_company(name: str) -> str:
    """Converts 'Étoile Services S.A.' to 'etoileservicessa' for email domains."""

    # Normalize accents (É -> E, ñ -> n, ü -> u)
    name = unicodedata.normalize('NFKD', name).encode('ascii', 'ignore').decode('ascii')

    # Lowercase
    name = name.lower()

    # Remove spaces and special characters
    name = re.sub(r'[^a-z0-9]', '', name)

    return name[:25]  # Limit length


def get_random_profile(country_code: str) -> dict:
    """
    Picks a perfectly matched profile (fullname, sex, DOB, birthplace, TIN).
    """
    cc = country_code.upper()
    pool = SEED_PROFILES.get(cc, SEED_PROFILES['GB'])

    fn_sex = random.choice(pool['firstnames_and_sex'])
    lastname = random.choice(pool['lastnames'])

    profile = {
        'fullname': f"{fn_sex['firstname']} {lastname}",
        'sex': fn_sex['sex'],
    }

    if cc in ['IT', 'FR']:
        profile['birthdate'] = random.choice(pool['birthdates'])
        profile['birthplace'] = random.choice(pool['birthplaces'])
        profile['tin'] = "" # Calculated dynamically in services.py
    else:
        # For DE/ES/GB, DOB and Birthplace aren't used for TIN calc
        profile['birthdate'] = ""
        profile['birthplace'] = ""
        profile['tin'] = random.choice(pool['tins'])

    return profile


def get_random_data(country_code: str, fake_type: str, **kwargs) -> str:
    """
    Generates standalone fake data based on the fake_type.
    """
    cc = country_code.upper()

    if fake_type == "id":
        return f"{cc}-{uuid.uuid4().hex[:6].upper()}"

    elif fake_type == "location":
        locations = SEED_LOCATIONS.get(cc, SEED_LOCATIONS['GB'])
        return random.choice(locations)

    elif fake_type == "amount":
        return f"{random.randint(9, 50)}0.000"

    elif fake_type == "company_name":
        parts = SEED_COMPANY_NAMES[cc]
        prefix = random.choice(parts['prefix'])
        suffix = random.choice(parts['suffix'])
        legal = random.choice(parts['legal'])
        return f"{prefix} {suffix} {legal}"

    elif fake_type == "iban":
        ibans = SEED_IBANS.get(cc, SEED_IBANS['GB'])
        return random.choice(ibans)

    elif fake_type == "vat":
        vats = SEED_VATS.get(cc, SEED_VATS['GB'])
        return random.choice(vats)

    elif fake_type == "ip":
        # Pull IP addresses from a GLOBAL pool to simulate cross-border fraud!
        return random.choice(SEED_IPS)

    elif fake_type == "phone":
        # prefix = INTL_PHONE_PREFIX.get(cc, INTL_PHONE_PREFIX["GB"])

        # Pull phone numbers from a GLOBAL pool to simulate cross-border fraud!
        # Pick a random country code from the available prefixes
        random_cc = random.choice(list(INTL_PHONE_PREFIX.keys()))
        prefix = INTL_PHONE_PREFIX.get(random_cc, INTL_PHONE_PREFIX["GB"])
        # Generate the number
        return f"{prefix} {random.randint(100, 999)}{random.randint(1000000, 9999999)}"

    elif fake_type == "email":
        # Get the company name from the kwargs context
        company_name = kwargs.get('company_name', "")
        company_slug = _slugify_company(company_name)

        # Italian PEC vs Standard Email
        if cc == 'IT':
            prefixes = ['info', 'amministrazione', 'segreteria']
            domains = ['pec.it', 'legalmail.it', 'postacert.it']
            return f"{random.choice(prefixes)}@{company_slug}.{random.choice(domains)}"
        else:
            prefixes = ['info', 'office', 'contact']
            return f"{random.choice(prefixes)}@{company_slug}.{cc.lower()}"


    return ""





